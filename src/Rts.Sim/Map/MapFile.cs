using System.IO.Compression;
using System.Numerics;
using Rts.Sim.Persistence;
using Rts.Sim.World;

namespace Rts.Sim.Map;

/// <summary>A map file that cannot be read (bad magic/version, damaged payload, hash mismatch).</summary>
public sealed class MapFileException(string message, Exception? inner = null) : Exception(message, inner);

/// <summary>Header of a map file: readable without decoding the terrain (menus list maps quickly).</summary>
public sealed class MapFileInfo
{
    /// <summary>File name without the extension: the id saves/replays and <c>--mapfile</c> use. Not stored in the file.</summary>
    public string Id = "";
    /// <summary>Full path of the file it was read from (null when decoded from bytes).</summary>
    public string? Path;
    public int Version = MapFile.Version;
    public string Name = "";
    public string Description = "";
    /// <summary>Start positions = most players (a game may use fewer, see <see cref="MapFile.TerrainFor"/>).</summary>
    public int Players;
    public int Width, Height;
    /// <summary>Heights stored as multiples of 2^-HeightBits (0 = exact float bits).</summary>
    public int HeightBits;
    /// <summary>Origin: generated by <see cref="MapGenerator"/> with these settings (informational only; the file is the map).</summary>
    public bool Generated;
    public MapPreset Preset;
    public int Seed;
    public float WaterAmount = -1;
    /// <summary>Content hash (<see cref="Hash64"/> of the uncompressed payload): identifies the map in saves/replays.</summary>
    public ulong Hash;

    public string HashHex => Hash.ToString("X16");
    public string SizeLabel => Width == Height ? $"{Width}" : $"{Width}x{Height}";
}

/// <summary>
/// (8b-2) Versioned map file (<c>data/maps/*.rtsmap</c>): heightmap, water level, deposits, start positions, props
/// (trees/rocks), name and origin. Layout: magic "RTSMAP" + u16 version + header block (<see cref="MapFileInfo"/>)
/// + u64 content hash + raw length + Brotli payload. Payload: size, water level, terrain seed, heights (integer
/// values = float bits or multiples of 2^-HeightBits, gradient-predicted residuals as zigzag varints), deposits,
/// starts, props (column order). The round trip is exact: <see cref="Decode"/> gives a <see cref="Terrain"/> with the
/// same heights/deposits/starts/props bits (passability is recomputed by the constructor). ARCHITECTURE "Map files".
/// </summary>
public sealed class MapFile
{
    public const string Extension = ".rtsmap";
    public const int Version = 1;
    private static ReadOnlySpan<byte> Magic => "RTSMAP"u8;

    public required MapFileInfo Info;
    /// <summary>The terrain with every start position of the file.</summary>
    public required Terrain Terrain;

    // ------------------------------------------------------------------ encode

    /// <summary>Encodes a terrain (lossless: heights are written as exact multiples of 2^-<paramref name="info"/>.HeightBits
    /// when they all are, else as exact float bits and HeightBits becomes 0). Fills <paramref name="info"/>'s Hash/size.</summary>
    public static byte[] Encode(Terrain t, MapFileInfo info)
    {
        var payload = EncodePayload(t, ref info.HeightBits);
        info.Width = t.Width;
        info.Height = t.Height;
        info.Players = t.StartPositions.Length;
        info.Version = Version;
        info.Hash = Hash64.Of(payload);
        var o = new ByteWriter(payload.Length / 3 + 4096);
        o.Bytes(Magic);
        o.Raw((ushort)Version);
        o.Block(HeaderBytes(info));
        o.Raw(info.Hash);
        o.VarU((ulong)payload.Length);
        var dst = new byte[BrotliEncoder.GetMaxCompressedLength(payload.Length)];
        if (!BrotliEncoder.TryCompress(payload, dst, out int n, quality: 9, window: 24)) throw new MapFileException("compression failed");
        o.Block(dst.AsSpan(0, n));
        return o.ToArray();
    }

    public static void Save(string path, Terrain t, MapFileInfo info)
    {
        var bytes = Encode(t, info);
        var dir = System.IO.Path.GetDirectoryName(System.IO.Path.GetFullPath(path));
        if (dir != null) Directory.CreateDirectory(dir);
        File.WriteAllBytes(path, bytes);
        info.Path = path;
        info.Id = IdOf(path);
    }

    private static byte[] HeaderBytes(MapFileInfo i)
    {
        var o = new ByteWriter(256);
        o.Str(i.Name);
        o.Str(i.Description);
        o.VarU((ulong)i.Players);
        o.VarU((ulong)i.Width);
        o.VarU((ulong)i.Height);
        o.U8((byte)i.HeightBits);
        o.U8(i.Generated ? (byte)1 : (byte)0);
        o.U8((byte)i.Preset);
        o.VarI(i.Seed);
        o.Raw(i.WaterAmount);
        return o.ToArray();
    }

    /// <summary>The content hash a terrain would get in a file (same bytes as <see cref="Encode"/> hashes).</summary>
    public static ulong ContentHash(Terrain t, int heightBits = 0) => Hash64.Of(EncodePayload(t, ref heightBits));

    private static byte[] EncodePayload(Terrain t, ref int heightBits)
    {
        int n = t.Heights.Length;
        var vals = new int[n];
        if (heightBits < 0 || heightBits > 20 || !TryQuantized(t.Heights, heightBits, vals)) heightBits = 0;
        if (heightBits == 0)
            for (int i = 0; i < n; i++) vals[i] = BitConverter.SingleToInt32Bits(t.Heights[i]);

        var o = new ByteWriter(n * 2 + t.Props.Length * 26 + 4096);
        o.Raw(t.Width);
        o.Raw(t.Height);
        o.Raw(t.WaterLevel);
        o.Raw(t.Seed);
        o.U8((byte)heightBits);
        int stride = t.Width + 1, rows = t.Height + 1;
        for (int z = 0; z < rows; z++)
        for (int x = 0; x < stride; x++)
        {
            int i = z * stride + x;
            o.VarU(ZigZag(unchecked(vals[i] - Predict(vals, x, z, stride))));
        }
        o.VarU((ulong)t.Deposits.Length);
        foreach (var d in t.Deposits) { o.Raw(d.Pos.X); o.Raw(d.Pos.Y); o.U8((byte)d.Type); }
        o.VarU((ulong)t.StartPositions.Length);
        foreach (var s in t.StartPositions) { o.Raw(s.X); o.Raw(s.Y); }
        var props = t.Props;
        o.VarU((ulong)props.Length);
        foreach (var p in props) o.U8((byte)p.Kind);
        foreach (var p in props) o.U8(p.Variant);
        foreach (var p in props) o.Raw(p.Pos.X);
        foreach (var p in props) o.Raw(p.Pos.Y);
        foreach (var p in props) o.Raw(p.Heading);
        foreach (var p in props) o.Raw(p.Radius);
        foreach (var p in props) o.Raw(p.Mass);
        foreach (var p in props) o.Raw(p.Energy);
        return o.ToArray();
    }

    private static bool TryQuantized(float[] h, int bits, int[] vals)
    {
        if (bits == 0) return false;
        float scale = MathF.ScaleB(1f, bits);
        for (int i = 0; i < h.Length; i++)
        {
            float k = h[i] * scale; // exact (power-of-two scale)
            if (k != MathF.Round(k) || MathF.Abs(k) > 1 << 23) return false;
            vals[i] = (int)k;
            // Bit-exact only (e.g. -0 would come back as +0).
            if (BitConverter.SingleToInt32Bits(vals[i] / scale) != BitConverter.SingleToInt32Bits(h[i])) return false;
        }
        return true;
    }

    /// <summary>Gradient predictor from the left, upper and upper-left vertex (wrapping int arithmetic).</summary>
    private static int Predict(int[] v, int x, int z, int stride)
    {
        if (z == 0) return x == 0 ? 0 : v[x - 1];
        int i = z * stride + x;
        if (x == 0) return v[i - stride];
        return unchecked(v[i - 1] + v[i - stride] - v[i - stride - 1]);
    }

    private static ulong ZigZag(int v) => (uint)((v << 1) ^ (v >> 31));
    private static int UnZigZag(ulong u) => (int)((uint)u >> 1) ^ -(int)((uint)u & 1);

    /// <summary>A copy of the terrain with heights rounded to multiples of 2^-bits (smaller files; the map file is then
    /// an exact copy of the returned terrain, not of the input). Deposits, starts and props are kept.</summary>
    public static Terrain Quantize(Terrain t, int bits)
    {
        float scale = MathF.ScaleB(1f, bits);
        var h = new float[t.Heights.Length];
        for (int i = 0; i < h.Length; i++) h[i] = MathF.Round(t.Heights[i] * scale) / scale + 0f; // + 0f: no -0
        return new Terrain(t.Width, t.Height, h, t.WaterLevel, t.Deposits, t.StartPositions, t.Seed) { Props = t.Props };
    }

    // ------------------------------------------------------------------ decode

    public static MapFile Load(string path)
    {
        byte[] bytes;
        try { bytes = File.ReadAllBytes(path); }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException) { throw new MapFileException($"Cannot read {System.IO.Path.GetFileName(path)}: {e.Message}", e); }
        var f = Decode(bytes);
        f.Info.Path = path;
        f.Info.Id = IdOf(path);
        return f;
    }

    /// <summary>Header only (no decompression).</summary>
    public static MapFileInfo ReadHeader(string path)
    {
        // The header is small and at the start; read a bounded prefix.
        using var fs = File.OpenRead(path);
        var buf = new byte[(int)Math.Min(fs.Length, 64 * 1024)];
        fs.ReadExactly(buf);
        var info = ReadHeader(new ByteReader(buf), out _);
        info.Path = path;
        info.Id = IdOf(path);
        return info;
    }

    public static MapFile Decode(byte[] bytes)
    {
        var r = new ByteReader(bytes);
        var info = ReadHeader(r, out ulong rawLen);
        try
        {
            var comp = r.Block();
            if (rawLen > 1u << 30) throw new MapFileException("Damaged map file (payload size)");
            var payload = new byte[rawLen];
            if (!BrotliDecoder.TryDecompress(comp, payload, out int got) || got != payload.Length)
                throw new MapFileException("Damaged map file (payload)");
            if (Hash64.Of(payload) != info.Hash) throw new MapFileException("Damaged map file (content hash mismatch)");
            var terrain = DecodePayload(payload, info);
            return new MapFile { Info = info, Terrain = terrain };
        }
        catch (SaveFormatException e) { throw new MapFileException("Damaged map file (" + e.Message + ")", e); }
    }

    private static MapFileInfo ReadHeader(ByteReader r, out ulong rawLen)
    {
        try
        {
            if (r.Remaining < 8 || !r.Take(Magic.Length).SequenceEqual(Magic)) throw new MapFileException("Not a map file");
            int version = r.Raw<ushort>();
            if (version < 1 || version > Version) throw new MapFileException($"Map file version {version} is not supported (this game reads up to {Version})");
            var h = new ByteReader(r.Block());
            var info = new MapFileInfo
            {
                Version = version,
                Name = h.Str() ?? "",
                Description = h.Str() ?? "",
                Players = (int)h.VarU(),
                Width = (int)h.VarU(),
                Height = (int)h.VarU(),
                HeightBits = h.U8(),
                Generated = h.U8() != 0,
                Preset = (MapPreset)h.U8(),
                Seed = (int)h.VarI(),
                WaterAmount = h.Raw<float>(),
            };
            info.Hash = r.Raw<ulong>();
            rawLen = r.VarU();
            return info;
        }
        catch (SaveFormatException e) { throw new MapFileException("Damaged map file (" + e.Message + ")", e); }
    }

    private static Terrain DecodePayload(byte[] payload, MapFileInfo info)
    {
        var r = new ByteReader(payload);
        int w = r.Raw<int>(), hgt = r.Raw<int>();
        if (w < 8 || hgt < 8 || w > 8192 || hgt > 8192 || w != info.Width || hgt != info.Height) throw new MapFileException("Damaged map file (size)");
        float water = r.Raw<float>();
        int seed = r.Raw<int>();
        int bits = r.U8();
        int stride = w + 1, rows = hgt + 1;
        var vals = new int[stride * rows];
        for (int z = 0; z < rows; z++)
        for (int x = 0; x < stride; x++)
            vals[z * stride + x] = unchecked(Predict(vals, x, z, stride) + UnZigZag(r.VarU()));
        var heights = new float[vals.Length];
        if (bits == 0) for (int i = 0; i < vals.Length; i++) heights[i] = BitConverter.Int32BitsToSingle(vals[i]);
        else
        {
            float scale = MathF.ScaleB(1f, bits);
            for (int i = 0; i < vals.Length; i++) heights[i] = vals[i] / scale;
        }
        var deposits = new Deposit[r.Count(r.Remaining / 9)];
        for (int i = 0; i < deposits.Length; i++)
        {
            float x = r.Raw<float>(), z = r.Raw<float>();
            deposits[i] = new Deposit(new Vector2(x, z), (DepositType)r.U8());
        }
        var starts = new Vector2[r.Count(r.Remaining / 8)];
        for (int i = 0; i < starts.Length; i++) { float x = r.Raw<float>(); starts[i] = new Vector2(x, r.Raw<float>()); }
        if (starts.Length < 1) throw new MapFileException("Damaged map file (no start positions)");
        int np = r.Count(r.Remaining / 26);
        var kind = r.Take(np).ToArray();
        var variant = r.Take(np).ToArray();
        var cols = new float[6][];
        for (int c = 0; c < 6; c++)
        {
            cols[c] = new float[np];
            r.Bytes(System.Runtime.InteropServices.MemoryMarshal.AsBytes(cols[c].AsSpan()));
        }
        var props = new MapProp[np];
        for (int i = 0; i < np; i++)
            props[i] = new MapProp((PropKind)kind[i], new Vector2(cols[0][i], cols[1][i]), cols[2][i], variant[i], cols[3][i], cols[4][i], cols[5][i]);
        return new Terrain(w, hgt, heights, water, deposits, starts, seed) { Props = props };
    }

    public static string IdOf(string path) => System.IO.Path.GetFileNameWithoutExtension(path);

    // ------------------------------------------------------------------ games on a map file

    /// <summary>
    /// The terrain for a game of <paramref name="players"/> armies: the file's terrain when every start is used,
    /// else a copy with a spread subset of the starts (farthest-point order from start 0, ties to the lower index),
    /// so <c>StartPositions[army]</c> stays the army's start everywhere (AI scouting, camera, fog).
    /// </summary>
    public Terrain TerrainFor(int players)
    {
        var all = Terrain.StartPositions;
        if (players >= all.Length) return Terrain;
        if (players < 1) throw new ArgumentOutOfRangeException(nameof(players));
        var starts = SpreadStarts(all, players).Select(i => all[i]).ToArray();
        return new Terrain(Terrain.Width, Terrain.Height, Terrain.Heights, Terrain.WaterLevel, Terrain.Deposits, starts, Terrain.Seed)
        { Props = Terrain.Props };
    }

    /// <summary>Indices of <paramref name="count"/> well-spread starts (deterministic; first = 0).</summary>
    public static int[] SpreadStarts(Vector2[] starts, int count)
    {
        var pick = new List<int> { 0 };
        while (pick.Count < count)
        {
            int best = -1;
            float bestD = -1;
            for (int i = 0; i < starts.Length; i++)
            {
                if (pick.Contains(i)) continue;
                float d = float.MaxValue;
                foreach (int j in pick) d = MathF.Min(d, Vector2.DistanceSquared(starts[i], starts[j]));
                if (d > bestD) { bestD = d; best = i; }
            }
            pick.Add(best);
        }
        return pick.ToArray();
    }
}
